"""Generate src/font.c (ASCII 32..126, 8x16) from a PSF1/PSF2 console font."""
import gzip, struct, sys

def load_psf(path):
    data = gzip.open(path).read() if path.endswith('.gz') else open(path, 'rb').read()
    if data[:2] == b'\x36\x04':  # PSF1
        charsize = data[3]
        return data[4:], charsize, 8, 1
    if data[:4] == b'\x72\xb5\x4a\x86':  # PSF2
        _, _, hdr, _, n, charsize, h, w = struct.unpack('<8I', data[:32])
        return data[hdr:], charsize, w, (w + 7) // 8
    raise SystemExit('not a PSF font')

glyphs, charsize, width, rowbytes = load_psf(sys.argv[1])
assert width == 8 and charsize == 16, (width, charsize)
out = ['/* Generated by tools/gen_font.py from %s */' % sys.argv[1].split('/')[-1],
       '#include "font.h"', '',
       'const unsigned char font8x16[95][16] = {']
for c in range(32, 127):
    g = glyphs[c * charsize:(c + 1) * charsize]
    out.append('  {' + ','.join('0x%02x' % b for b in g) + '}, /* %r */' % chr(c))
out.append('};')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
