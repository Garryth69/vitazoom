"""Generate src/font_big.c: 12x24 antialiased glyphs (2 bits/pixel) for
ASCII 32..126 and Latin-1 160..255, rendered from a TTF with Pillow."""
import sys
from PIL import Image, ImageDraw, ImageFont

W, H = 12, 24
ttf, out_path = sys.argv[1], sys.argv[2]
size = int(sys.argv[3]) if len(sys.argv) > 3 else 19
font = ImageFont.truetype(ttf, size)
ascent, descent = font.getmetrics()
top = (H - (ascent + descent)) // 2

chars = list(range(32, 127)) + list(range(160, 256))
lines = ['/* Generated by tools/gen_bigfont.py from %s, %dpx */' % (ttf.split('/')[-1], size),
         '#include "font.h"', '',
         '/* index: ASCII c-32, Latin-1 95+(c-160). 24 rows x 3 bytes, 2 bpp, MSB = left */',
         'const unsigned char font_big[%d][%d] = {' % (len(chars), H * 3)]
for c in chars:
    img = Image.new('L', (W, H), 0)
    d = ImageDraw.Draw(img)
    ch = chr(c)
    bbox = font.getbbox(ch)
    adv = font.getlength(ch)
    x = int(round((W - adv) / 2))
    d.text((x, top), ch, fill=255, font=font)
    px = img.load()
    data = []
    for y in range(H):
        for bx in range(3):
            b = 0
            for k in range(4):
                v = px[bx * 4 + k, y]
                q = (v * 3 + 127) // 255
                b |= q << (6 - 2 * k)
            data.append(b)
    lines.append('  {' + ','.join('0x%02x' % b for b in data) + '}, /* U+%04X */' % c)
lines.append('};')
open(out_path, 'w').write('\n'.join(lines) + '\n')

